#!/usr/bin/env bash
#
# client-setup.sh — get this machine ready to play TES3MP.
#
#   1. find your Morrowind "Data Files" directory
#   2. download, verify and unpack the TES3MP client into the runtime dir
#   3. write an openmw.cfg that loads Morrowind in the order servers require
#
# Every step is skipped when it is already done, so running this again is
# quick and safe. See --help for options.

set -euo pipefail

# --- locate this script (works from any cwd and through symlinks) ------------
SOURCE=${BASH_SOURCE[0]}
while [ -L "$SOURCE" ]; do
  DIR=$(cd -P "$(dirname "$SOURCE")" && pwd)
  SOURCE=$(readlink "$SOURCE")
  [[ $SOURCE != /* ]] && SOURCE=$DIR/$SOURCE
done
SCRIPT_DIR=$(cd -P "$(dirname "$SOURCE")" && pwd)
# shellcheck source-path=SCRIPTDIR source=lib.sh
. "$SCRIPT_DIR/lib.sh"

# First line of every openmw.cfg this script writes. Its presence is how we
# tell our own file from one the user (or OpenMW's launcher) created.
readonly CFG_MARKER='# Generated by my-tes3mp'
# Dropped into the client directory once it is completely installed.
readonly INSTALL_STAMP=.my-tes3mp-install

usage() {
  cat <<EOF
Usage: client-setup.sh [options]

Installs the TES3MP $TES3MP_VERSION client and configures it to use your existing
Morrowind install. Safe to re-run: steps that are already done are skipped.

Options:
  --force       Replace an openmw.cfg that this tool did not create (a
                timestamped backup is kept next to it), and regenerate the
                config even if it looks up to date.
  --reinstall   Unpack the client again even if it is already installed.
  --detect      Only print the Morrowind "Data Files" directory that would be
                used, then exit. Changes nothing.
  -q, --quiet   Say nothing when there is nothing to do: only report work
                actually done, warnings and errors.
  -h, --help    Show this help.

Environment (each may also be set in $MY_TES3MP_ROOT/.env):
  MORROWIND_DATA        Path to Morrowind's "Data Files" directory (the one
                        holding Morrowind.esm). Auto-detected from Steam,
                        GOG, Wine, Lutris and Heroic locations when unset.
  MORROWIND_ENCODING    win1252 (default, Western), win1250 (Central/Eastern
                        European) or win1251 (Cyrillic) — match your edition.

Environment only:
  MY_TES3MP_RUNTIME     Where to install the client.
                        Default: $MY_TES3MP_ROOT/.runtime
  TES3MP_CLIENT_TARBALL Use this already-downloaded release tarball instead
                        of downloading (it is still checksum-verified).
  XDG_CONFIG_HOME       openmw.cfg is written to \$XDG_CONFIG_HOME/openmw/
                        (default ~/.config/openmw/), OpenMW's standard place.

Exit codes:
  0 ready   $EX_USAGE bad usage   $EX_DEPENDENCY missing host tool / unsupported machine
  $EX_NO_MORROWIND Morrowind not found   $EX_DOWNLOAD download or checksum failure
  $EX_CONFIG an existing openmw.cfg needs --force   $EX_FAIL anything else
EOF
}

# --- temp files --------------------------------------------------------------
# Everything temporary lives in directories listed here and is removed on
# exit, however the script ends.
CLEANUP_DIRS=()
cleanup() {
  local dir
  for dir in ${CLEANUP_DIRS[@]+"${CLEANUP_DIRS[@]}"}; do
    rm -rf -- "$dir"
  done
}
trap cleanup EXIT

# --- step 1: Morrowind -------------------------------------------------------
# Sets MW_DATA (absolute path of "Data Files") and MW_FOUND_BY (how we know).
MW_DATA=''
MW_FOUND_BY=''
locate_morrowind() {
  local configured previous

  # 1. An explicit setting always wins, and a wrong one is an error rather
  #    than a reason to quietly pick some other install.
  configured=$(setting MORROWIND_DATA)
  if [ -n "$configured" ]; then
    MW_DATA=$(normalize_morrowind_data "$configured") ||
      die_with "$EX_NO_MORROWIND" "MORROWIND_DATA is set to '$configured', but that folder has no Morrowind.esm and Morrowind.bsa.
Point it at Morrowind's \"Data Files\" directory (or the install folder that contains it)."
    MW_FOUND_BY='set by MORROWIND_DATA'
    return 0
  fi

  # 2. The location a previous run of this script configured, while it is
  #    still valid. Keeps a one-off MORROWIND_DATA=... setup working later.
  if [ -f "$CFG_FILE" ] && cfg_is_ours "$CFG_FILE"; then
    previous=$(cfg_values "$CFG_FILE" data | tail -n 1)
    previous=$(cfg_unquote "$previous")
    if [ -n "$previous" ] && is_morrowind_data "$previous"; then
      MW_DATA=$previous
      MW_FOUND_BY='from the existing config'
      return 0
    fi
  fi

  # 3. Look in the usual places.
  if MW_DATA=$(detect_morrowind_data); then
    MW_FOUND_BY='auto-detected'
    return 0
  fi

  die_with "$EX_NO_MORROWIND" "could not find a Morrowind installation.

TES3MP plays with the data files of your own copy of Morrowind (Steam, GOG
or retail). I looked in every Steam library (native, Flatpak and Snap) and
in the usual GOG, Wine, Lutris, Heroic and Bottles locations.

If Morrowind is installed somewhere else, tell me where its \"Data Files\"
folder (the one containing Morrowind.esm) is, by adding this line to
$MY_TES3MP_ROOT/.env

    MORROWIND_DATA=/path/to/Morrowind/Data Files

or by setting MORROWIND_DATA in the environment for this command.

If it is not installed yet: in Steam, enable Steam Play (Proton) for all
titles under Settings > Compatibility, then install Morrowind and re-run."
}

# --- step 2: the client ------------------------------------------------------
client_is_current() {
  local dir stamp=''
  dir=$(client_dir)
  [ -x "$dir/tes3mp.x86_64" ] && [ -f "$dir/$INSTALL_STAMP" ] || return 1
  IFS= read -r stamp <"$dir/$INSTALL_STAMP" || true
  [ "$stamp" = "$TES3MP_VERSION $TES3MP_SHA256" ]
}

verify_tarball() {
  [ "$(sha256_of "$1")" = "$TES3MP_SHA256" ]
}

# fetch URL DEST [CURL OPTIONS...] — one download attempt, with curl's own
# retries for timeouts and 5xx answers.
fetch() {
  local url=$1 dest=$2
  shift 2
  # A progress bar for people, plain errors for logs and pipes.
  local progress=(--silent --show-error)
  if [ -t 2 ]; then
    progress=(--progress-bar)
  fi
  rm -f -- "$dest"
  curl --fail --location --connect-timeout 20 --retry 3 --retry-delay 2 \
    "${progress[@]}" "$@" --output "$dest" "$url"
}

# Sets TARBALL to a verified copy of the release tarball.
TARBALL=''
obtain_tarball() {
  local cache part

  if [ -n "${TES3MP_CLIENT_TARBALL:-}" ]; then
    [ -f "$TES3MP_CLIENT_TARBALL" ] ||
      die_with "$EX_DOWNLOAD" "TES3MP_CLIENT_TARBALL points at '$TES3MP_CLIENT_TARBALL', which does not exist"
    step "Verifying $TES3MP_CLIENT_TARBALL"
    verify_tarball "$TES3MP_CLIENT_TARBALL" ||
      die_with "$EX_DOWNLOAD" "checksum mismatch for $TES3MP_CLIENT_TARBALL
  expected sha256 $TES3MP_SHA256
  got             $(sha256_of "$TES3MP_CLIENT_TARBALL")
It is not the TES3MP $TES3MP_VERSION Linux client release ($TES3MP_TARBALL)."
    TARBALL=$TES3MP_CLIENT_TARBALL
    return 0
  fi

  cache=$(runtime_dir)/cache/$TES3MP_TARBALL
  part=$cache.part
  mkdir -p "$(dirname "$cache")"

  if [ -f "$cache" ]; then
    if verify_tarball "$cache"; then
      info "Using the already-downloaded $TES3MP_TARBALL"
      TARBALL=$cache
      return 0
    fi
    warn "cached download is corrupt, fetching it again"
    rm -f -- "$cache"
  fi

  step "Downloading the TES3MP $TES3MP_VERSION client (about 60 MB)"
  if ! fetch "$TES3MP_URL" "$part"; then
    warn "download from github.com failed, trying the GitHub API mirror of the same file"
    if ! fetch "$TES3MP_API_URL" "$part" --header 'Accept: application/octet-stream'; then
      rm -f -- "$part"
      die_with "$EX_DOWNLOAD" "could not download the TES3MP client. Check your connection and try again,
or download it yourself from
  $TES3MP_URL
and re-run with TES3MP_CLIENT_TARBALL=/path/to/$TES3MP_TARBALL"
    fi
  fi

  # Only a file that passed verification ever gets the final name.
  if ! verify_tarball "$part"; then
    local got
    got=$(sha256_of "$part")
    rm -f -- "$part"
    die_with "$EX_DOWNLOAD" "the downloaded client failed checksum verification and was deleted
  expected sha256 $TES3MP_SHA256
  got             $got"
  fi
  mv -f -- "$part" "$cache"
  TARBALL=$cache
}

# Warn about shared libraries the client needs but the host lacks. The
# release bundles most of its dependencies in lib/; the rest (OpenGL, SDL's
# system backends, ...) must come from the distribution.
check_client_libraries() {
  local dir missing
  dir=$(client_dir)
  command -v ldd >/dev/null 2>&1 || return 0
  missing=$(LD_LIBRARY_PATH="$dir/lib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}" \
    ldd "$dir/tes3mp.x86_64" 2>/dev/null | awk '/not found/ { print $1 }' | sort -u | tr '\n' ' ') || true
  if [ -n "$missing" ]; then
    warn "the client needs system libraries that are not installed: $missing
         Install them with your package manager, or the game will not start."
  fi
}

install_client() {
  local runtime dir stage tar_opts

  runtime=$(runtime_dir)
  dir=$(client_dir)

  if [ "$REINSTALL" = 0 ] && client_is_current; then
    return 0
  fi

  obtain_tarball

  # Unpack next to the final location, then swap the finished tree into
  # place, so an interrupted run never leaves a half-installed client.
  mkdir -p "$runtime"
  stage=$(mktemp -d "$runtime/.install.XXXXXX")
  CLEANUP_DIRS+=("$stage")

  step "Unpacking the client into $dir"
  tar_opts=(--no-same-owner)
  # The release archive ends with a short end-of-archive marker; GNU tar
  # warns about it ("A lone zero block") although nothing is wrong.
  if tar --version 2>/dev/null | grep -q 'GNU tar'; then
    tar_opts+=(--warning=no-alone-zero-block)
  fi
  tar -xzf "$TARBALL" -C "$stage" "${tar_opts[@]}"
  [ -x "$stage/TES3MP/tes3mp.x86_64" ] ||
    die "the archive did not contain TES3MP/tes3mp.x86_64 — unexpected release layout"

  printf '%s %s\n' "$TES3MP_VERSION" "$TES3MP_SHA256" >"$stage/TES3MP/$INSTALL_STAMP"
  if [ -e "$dir" ]; then
    mv -- "$dir" "$stage/previous"
  fi
  mv -- "$stage/TES3MP" "$dir"

  check_client_libraries
  DID_WORK=1
}

# --- step 3: openmw.cfg ------------------------------------------------------
cfg_is_ours() {
  grep -qF -- "$CFG_MARKER" "$1" 2>/dev/null
}

# cfg_signature FILE — the settings this script is responsible for, pulled
# out of an openmw.cfg in a fixed key order so that two files can be
# compared regardless of comments or of how the keys are interleaved.
cfg_signature() {
  local key value
  for key in data content fallback-archive encoding; do
    while IFS= read -r value; do
      printf '%s=%s\n' "$key" "$value"
    done < <(cfg_values "$1" "$key")
  done
}

# Print the data/content/fallback-archive/encoding lines for MW_DATA.
#
# Content order matters: TES3MP servers reject clients whose load order
# differs from theirs, and the stock server expects Morrowind, Tribunal,
# Bloodmoon. (Morrowind.ini often lists them alphabetically, which is why
# the order is fixed here instead of imported.) Expansions that are not
# installed are left out.
managed_lines() {
  local i master archive
  local content=() archives=()
  for i in "${!MORROWIND_MASTERS[@]}"; do
    master=${MORROWIND_MASTERS[$i]}
    archive=${MORROWIND_ARCHIVES[$i]}
    find_ci "$MW_DATA" "$master" >/dev/null || continue
    content+=("$master")
    if find_ci "$MW_DATA" "$archive" >/dev/null; then
      archives+=("$archive")
    else
      warn "$master is installed but $archive is missing from $MW_DATA — its models and textures will not load"
    fi
  done
  printf 'data=%s\n' "$(cfg_quote "$MW_DATA")"
  printf 'content=%s\n' "${content[@]}"
  printf 'fallback-archive=%s\n' "${archives[@]}"
  printf 'encoding=%s\n' "$ENCODING"
}

# Print the "fallback=" lines for this Morrowind install: the game settings
# (weather, fonts, movies, level-up texts, ...) that the original engine
# reads from Morrowind.ini. The client's bundled openmw-iniimporter does the
# conversion; we take only its fallback lines, because the data, content and
# archive lines are written by managed_lines above.
import_ini_fallbacks() {
  local ini work dir
  dir=$(client_dir)

  if ! ini=$(find_ci "$(dirname "$MW_DATA")" Morrowind.ini); then
    warn "no Morrowind.ini next to $MW_DATA — using the client's built-in default game settings"
    return 0
  fi

  work=$(mktemp -d "${TMPDIR:-/tmp}/my-tes3mp.XXXXXX")
  CLEANUP_DIRS+=("$work")
  : >"$work/in.cfg"
  # Run the real binary rather than the release's wrapper script, which
  # breaks when the install path contains spaces.
  if ! LD_LIBRARY_PATH="$dir/lib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}" \
    "$dir/openmw-iniimporter.x86_64" \
    --ini "$ini" --cfg "$work/in.cfg" --output "$work/out.cfg" \
    --no-archives --encoding "$ENCODING" >"$work/importer.log" 2>&1; then
    warn "openmw-iniimporter could not read $ini — using the client's built-in default game settings. Its output was:"
    sed 's/^/    /' "$work/importer.log" >&2
    return 0
  fi
  grep '^fallback=' "$work/out.cfg" || true
}

backup_cfg() {
  local backup
  backup=$CFG_FILE.bak-$(date +%Y%m%d-%H%M%S)
  # Never overwrite an earlier backup made within the same second.
  while [ -e "$backup" ]; do
    backup=$backup.1
  done
  cp -p -- "$CFG_FILE" "$backup"
  step "Kept the previous config as $backup"
}

write_cfg() {
  local wanted=$1 tmp
  mkdir -p "$CFG_DIR"
  tmp=$(mktemp "$CFG_DIR/.openmw.cfg.XXXXXX")
  {
    printf '%s (scripts/client-setup.sh) on %s.\n' "$CFG_MARKER" "$(date '+%Y-%m-%d %H:%M:%S')"
    cat <<'EOF'
#
# This is the standard OpenMW user config, set up for TES3MP. client-setup.sh
# leaves it alone as long as the data=, content=, fallback-archive= and
# encoding= lines below are what it expects, so you can add other settings.
# If those lines stop matching (for example Morrowind moved), the whole file
# is regenerated and this version is kept as openmw.cfg.bak-<timestamp>.
#
# Do not reorder the content= lines: TES3MP servers refuse clients whose
# load order differs from theirs.

EOF
    printf '%s\n' "$wanted"
    cat <<'EOF'

# Game settings imported from Morrowind.ini by openmw-iniimporter.
EOF
    import_ini_fallbacks
  } >"$tmp"
  [ ! -e "$CFG_FILE" ] || backup_cfg
  chmod 644 "$tmp"
  mv -f -- "$tmp" "$CFG_FILE"
  DID_WORK=1
}

configure_openmw() {
  local wanted current
  wanted=$(managed_lines)

  if [ ! -e "$CFG_FILE" ]; then
    step "Writing $CFG_FILE"
    write_cfg "$wanted"
    return 0
  fi

  current=$(cfg_signature "$CFG_FILE")
  if [ "$FORCE" = 0 ] && [ "$current" = "$wanted" ]; then
    if ! cfg_is_ours "$CFG_FILE"; then
      info "$CFG_FILE was not created by my-tes3mp but already loads Morrowind correctly — leaving it untouched"
    fi
    return 0
  fi

  if cfg_is_ours "$CFG_FILE" || [ "$FORCE" = 1 ]; then
    step "Updating $CFG_FILE"
    write_cfg "$wanted"
    return 0
  fi

  # Somebody else's config that does not match: possibly a modded OpenMW
  # setup. Replacing it is the user's call, not ours.
  die_with "$EX_CONFIG" "$CFG_FILE already exists and was not created by my-tes3mp.
TES3MP reads the same file, and it does not load Morrowind the way a TES3MP
server requires. It currently has:

$(printf '%s\n' "${current:-(no data/content/fallback-archive lines)}" | sed 's/^/    /')

but needs exactly:

$(printf '%s\n' "$wanted" | sed 's/^/    /')

Nothing was changed. Either edit the file yourself, or re-run with --force
to replace it (the current file is first copied to openmw.cfg.bak-<timestamp>
in the same folder, so nothing is lost)."
}

# --- main --------------------------------------------------------------------
FORCE=0
REINSTALL=0
DETECT_ONLY=0
DID_WORK=0

main() {
  while [ $# -gt 0 ]; do
    case $1 in
      --force) FORCE=1 ;;
      --reinstall) REINSTALL=1 ;;
      --detect) DETECT_ONLY=1 ;;
      -q | --quiet) export MY_TES3MP_QUIET=1 ;;
      -h | --help)
        usage
        exit 0
        ;;
      *) die_with "$EX_USAGE" "unknown option '$1' — see --help" ;;
    esac
    shift
  done

  [ -n "${HOME:-}" ] || [ -n "${XDG_CONFIG_HOME:-}" ] ||
    die "neither HOME nor XDG_CONFIG_HOME is set — cannot tell where the config belongs"
  CFG_DIR=$(openmw_config_dir)
  CFG_FILE=$CFG_DIR/openmw.cfg

  ENCODING=$(setting MORROWIND_ENCODING win1252)
  case $ENCODING in
    win1250 | win1251 | win1252) ;;
    *) die_with "$EX_USAGE" "MORROWIND_ENCODING must be win1250, win1251 or win1252 (got '$ENCODING')" ;;
  esac

  # Check the host before doing anything, so a missing tool is reported as
  # such rather than as some confusing failure halfway through. The
  # download tools are only needed when the client has to be installed.
  require_cmds find sed grep
  if [ "$DETECT_ONLY" = 0 ]; then
    require_x86_64_linux
    if [ "$REINSTALL" = 1 ] || ! client_is_current; then
      local needed=(tar sha256sum)
      [ -n "${TES3MP_CLIENT_TARBALL:-}" ] || needed+=(curl)
      require_cmds "${needed[@]}"
    fi
  fi

  # Morrowind first: it is the step most likely to need the user's help,
  # and there is no point downloading anything without it.
  locate_morrowind
  if [ "$DETECT_ONLY" = 1 ]; then
    printf '%s\n' "$MW_DATA"
    exit 0
  fi

  info "Morrowind data: $MW_DATA ($MW_FOUND_BY)"
  install_client
  configure_openmw

  if [ "$DID_WORK" = 1 ]; then
    info "Ready. Client: $(client_dir)"
    info "       Config: $CFG_FILE"
  else
    info "TES3MP $TES3MP_VERSION client is already set up — nothing to do"
  fi
}

main "$@"
